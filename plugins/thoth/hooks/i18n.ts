const TABLES: Record<Lang, Record<Key, string>> = { en: EN, 'zh-TW': ZH_TW }

/** The label for `key` in `lang`, its `{name}` slots filled from `vars`. */
export function t(lang: Lang, key: Key, vars: Record<string, string | number> = {}): string {
  return TABLES[lang][key].replace(/\{(\w+)\}/g, (slot, name: string) =>
    name in vars ? String(vars[name]) : slot,
  )
}

/** Whether `key` names a label, for keys built from thoth's own words (a status, a window name). */
export function hasKey(key: string): key is Key {
  return key in EN
}
